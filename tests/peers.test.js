let fails=0;const check=(n,ok,x='')=>{if(!ok)fails++;console.log(`${ok?'PASS':'FAIL'}  ${n} ${x}`);};
const p=await (await b.newContext({viewport:{width:800,height:500}})).newPage();const errs=[];p.on('pageerror',e=>errs.push(e.message));
await p.goto('file://'+path.resolve(__dirname,'peers-local.html'));await p.waitForTimeout(2500);
const d=(f,...a)=>p.evaluate(([f,a])=>window.__debug[f](...a),[f,a]);
await d('play');await d('mockPeers',[]);
for(const m of ['gold','diamond','wood','stone']) await d('give',m,50);
for(const r of ['sword1','armor2','shield1','pick_diamond']) await d('craft',r);await d('selectSlot',9);
const mine=await d('sendNow');check('own presence carries gear [sword,armor,shield,slot,pickaxe]',JSON.stringify(mine&&mine.g)==='[1,2,1,9,4]',JSON.stringify(mine&&mine.g));
const base={x:22.5,y:14,z:25.5,yaw:0,dead:false};
await d('mockPeers',[{id:'a1',pr:{...base}},{id:'b2',pr:{...base,x:24.5,g:[2,2,2,6,0]}},{id:'c3',pr:{...base,x:26.5,g:[0,1,0,9,3]}},{id:'d4',pr:{...base,x:28.5,g:'garbage'}}]);
