const { chromium } = require('playwright'); const path=require('path');
(async()=>{const b=await chromium.launch({executablePath:'/opt/pw-browsers/chromium',args:['--use-gl=swiftshader','--enable-webgl','--ignore-gpu-blocklist']});
let fails=0;const check=(n,ok,x='')=>{if(!ok)fails++;console.log(`${ok?'PASS':'FAIL'}  ${n} ${x}`);};
const p=await (await b.newContext({viewport:{width:800,height:500}})).newPage();const errs=[];p.on('pageerror',e=>errs.push(e.message));
await p.goto('file://'+path.resolve(__dirname,'weather-local.html'));await p.waitForTimeout(2500);
const ev=(f)=>p.evaluate(f);
await ev(()=>{window.__debug.stopTimer();window.__debug.setT(0.5);});
check('Fog is appended to the weather list (indexes of the others unchanged)',JSON.stringify(await ev(()=>window.__debug.names()))==='["Clear","Cloudy","Rain","Thunderstorm","Fog"]');
const clear=await ev(()=>{window.__debug.setState(0);return window.__debug.settle(60);});
const fog=await ev(()=>{window.__debug.setState(4);return window.__debug.settle(60);});
console.log('clear',JSON.stringify(clear),'fog',JSON.stringify(fog));
check('fog closes in the view distance',fog.far<clear.far*0.6&&fog.near<clear.near*0.4,`far ${clear.far.toFixed(0)} -> ${fog.far.toFixed(0)}`);
check('fog is not rain',fog.rain<0.05);
check('the weather pill says Fog',(await ev(()=>window.__debug.pill()))==='Fog');
const back=await ev(()=>{window.__debug.setState(0);return window.__debug.settle(80);});
check('it lifts again when the weather clears',back.far>clear.far*0.95,`far ${back.far.toFixed(0)}`);
const night=await ev(()=>{window.__debug.setT(0.0);window.__debug.setState(4);return window.__debug.settle(60);});
check('fog also works at night',night.far<clear.far*0.6);
const chain=await ev(()=>window.__debug.chain());
check('fog turns up in the random weather (and not too often)',chain[4]>100&&chain[4]<1200,JSON.stringify(chain));
check('every weather state is reachable',[0,1,2,3,4].every(k=>chain[k]>0),JSON.stringify(chain));
check('no page errors',errs.length===0,errs.join('|'));
console.log(fails?'FAILED':'ALL PASSED');await b.close();})();
